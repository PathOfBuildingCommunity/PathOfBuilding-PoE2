-- 显示资源长期契约：按稳定 key 查找，格式和输入转换互不混用。
return function(equal)
	local LineTemplates = dofile('Modules/Localisation/LineTemplates.lua')
	local line, lineValues = LineTemplates.Compile('Adds (1.20-3.40) to (5-9) Damage\n+10 to Life')
	equal(line, 'Adds {value_1} to {value_2} Damage\n+{value_3} to Life', '属性行命名范围参数')
	equal(lineValues.value_1, '(1.20-3.40)', '属性行保留输入精度')
	local reference = LineTemplates.Bind('test.line', '+10 to Life')
	equal(LineTemplates.Parameters(reference, '+25 to Life').value_1, '25', '属性增效沿用原引用')
	equal(LineTemplates.Parameters(reference, '+25 to Mana'), nil, '动态替换正文不能沿用旧引用')
	local ModifierInputs = dofile('Modules/Localisation/ModifierInputs.lua')
	local inputs = ModifierInputs.New({ { '', '+{value_1} to Life', 'life' } }, { en = { life = { text = 'Life plus {value_1}' } } })
	local bound = inputs:Bind('', { '+25 to Life' })
	equal(bound[1].key, 'life', '英文显示措辞变化不改变输入规则引用')
	equal(LineTemplates.Parameters(bound[1], '+50 to Life').value_1, '50', '装备已绑定引用接受新数值')
	equal(#inputs:Bind('', { 'My unknown modifier' }), 0, '未知装备输入不猜测身份')
	local ambiguous = ModifierInputs.New({ { '', '{value_1} Close', 'close' }, { '', '{value_1} Close', 'near' } }, {
		en = { close = { text = '{value_1} Close' }, near = { text = '{value_1} Close' } },
		['zh-CN'] = { close = { text = '关闭 {value_1}' }, near = { text = '接近 {value_1}' } },
	})
	equal(#ambiguous:Bind('', { '10 Close' }), 0, '输入语法用途歧义不能任选显示 key')
	local StatTemplates = dofile('Modules/Localisation/StatTemplates.lua')
	local text, slots = StatTemplates.Compile('{0:+d} to maximum Life\\n{1}% increased Damage')
	equal(text, '{value_1_plus} to maximum Life\n{value_2}% increased Damage', '属性模板命名参数和换行')
	local values = StatTemplates.Parameters(slots, { { min = 10, max = 20, fmt = 'd' }, { min = 12.34, max = 12.34, fmt = 'g' } })
	equal(values.value_1_plus, '+(10-20)', '属性正号范围格式')
	equal(values.value_2, '12.34', '属性变换精度保留')
	local _, qualitySlots = StatTemplates.Compile('Gains a Stage every {0} seconds, up to a maximum of {1} Stages')
	local quality = StatTemplates.Parameters(qualitySlots, { { min = 2, max = 2 }, { min = 5, max = 5 } }, function(value, index, first)
		return first and '(0-' .. value .. ')' or value
	end)
	equal(quality.value_1, '(0-2)', '品质范围仅处理首个数值')
	equal(quality.value_2, '5', '品质范围保留后续数值')
	local _, negative = StatTemplates.Compile('{0:-d}')
	equal(StatTemplates.Parameters(negative, { { min = -20, max = -10, fmt = 'd' } }).value_1_minus, '-(20-10)', '属性负数范围保留旧顺序')
	local description = { limit = { { 1, '#' } } }
	local identity = StatTemplates.Identity('skill_stat_descriptions', { 'maximum_life' }, description)
	description.text = 'Changed English'
	equal(StatTemplates.Identity('skill_stat_descriptions', { 'maximum_life' }, description), identity, '属性身份不依赖英文措辞')
	local Messages = dofile('Modules/Localisation/Messages.lua')
	local newlines = Messages.New()
	newlines:LoadCSV('en', 'key,text\r\nexample.crlf,"First\r\nSecond {value}"\r\nexample.lf,"First\nSecond {value}"\n')
	equal(newlines:Text('example.crlf', { value = 'A\r\nB' }), 'First\nSecond A\r\nB', 'CRLF 资源模板规范换行但保留参数原文')
	equal(newlines:Text('example.lf', { value = 'A' }), 'First\nSecond A', 'LF 资源模板保持换行')
	local catalog = Messages.New()
	catalog:LoadCSV('en', 'key,text\nitem.level,Requires Level {level:d}\nsummary.rate,{name}: {rate:.2f}%\nsummary.repeat,{name} / {name}\nsummary.order,{first} vs {second}\nsummary.braces,{{value}} = {value}\ncontext.close,Close\ncontext.near,Close\nonly.english,English {value}\n')
	catalog:LoadCSV('zh-CN', 'key,text\nitem.level,需求等级 {level:d}\nsummary.rate,{name}：{rate:.2f}%\nsummary.repeat,{name}、{name}\nsummary.order,{second} 对 {first}\nsummary.braces,{{数值}} = {value}\ncontext.close,关闭\ncontext.near,接近\n')
	catalog:Validate()
	equal(catalog:Text('item.level', { level = 20 }, { 'zh-CN' }), '需求等级 20', '稳定 key 与整数参数')
	equal(catalog:Text('summary.rate', { name = '^7Fireball^8', rate = 12.345 }, { 'zh-CN' }), '^7Fireball^8：12.35%', '参数颜色和小数百分比')
	equal(catalog:Text('summary.order', { first = 'A', second = 'B' }, { 'zh-CN' }), 'B 对 A', '命名参数重排')
	equal(catalog:Text('summary.repeat', { name = '中文' }, { 'zh-CN' }), '中文、中文', '同一个命名参数重复使用')
	equal(catalog:Text('summary.braces', { value = 0 }, { 'zh-CN' }), '{数值} = 0', '字面花括号与零值')
	equal(catalog:Text('context.close', nil, { 'zh-CN' }), '关闭', '相同英文的关闭用途')
	equal(catalog:Text('context.near', nil, { 'zh-CN' }), '接近', '相同英文的接近用途')
	local nested = { name = Messages.Ref('context.close') }
	equal(catalog:Text('summary.repeat', nested, { 'zh-CN' }), '关闭、关闭', '嵌套 key 参数使用中文')
	equal(catalog:Text('summary.repeat', nested, { 'en' }), 'Close / Close', '同一嵌套参数引用切换英文')
	equal(catalog:Text('only.english', { value = 'A\nB' }, { 'zh-CN' }), 'English A\nB', '缺失译文回退英文并保留参数换行')
	local changed = Messages.New()
	changed:LoadCSV('en', 'item.level,Minimum level: {level:d}\n')
	changed:LoadCSV('zh-CN', 'item.level,需求等级 {level:d}\n')
	changed:Validate()
	equal(changed:Text('item.level', { level = 20 }, { 'zh-CN' }), '需求等级 20', '修改英文措辞不影响现有 key 译文')

	-- 错误必须包含 key 或来源，不能返回缺值句子或静默覆盖。
	local function fails(callback, fragment, label)
		local ok, message = pcall(callback)
		equal(ok, false, label .. ' 被拒绝')
		equal(tostring(message):find(fragment, 1, true) ~= nil, true, label .. ' 可定位')
	end
	fails(function() catalog:Text('missing.key') end, 'missing.key', '未知 key')
	fails(function() catalog:Text('item.level', { }) end, 'level', '缺失参数')
	fails(function() catalog:Text('item.level', { level = 20, extra = 1 }) end, 'extra', '多余参数')
	fails(function() catalog:Text('item.level', { level = 'invalid' }) end, 'item.level', '错误数字参数')
	fails(function() catalog:LoadCSV('en', 'item.level,Other\n', 'duplicate.csv') end, 'duplicate.csv', '重复 key')
	fails(function() catalog:LoadCSV('en', 'bad.columns,A,B\n', 'columns.csv') end, 'columns.csv', '多余 CSV 列')
	fails(function() catalog:LoadCSV('en', 'bad.key,Text {0}\n') end, 'bad.key', '编号参数不能冒充命名参数')
	fails(function() catalog:LoadCSV('en', 'bad.format,{value:q}\n') end, 'bad.format', '无效参数格式')
	local mismatch = Messages.New()
	mismatch:LoadCSV('en', 'test.key,{value:.2f}\n')
	mismatch:LoadCSV('zh-CN', 'test.key,{value:d}\n')
	fails(function() mismatch:Validate() end, 'test.key', '译文参数格式改变')
	local missing = Messages.New()
	missing:LoadCSV('en', 'test.key,{value}\n')
	missing:LoadCSV('zh-CN', 'test.key,缺失参数\n')
	fails(function() missing:Validate() end, 'value', '译文丢失参数')
	local extra = Messages.New()
	extra:LoadCSV('en', 'test.key,Text\n')
	extra:LoadCSV('zh-CN', 'test.key,{extra}\n')
	fails(function() extra:Validate() end, 'extra', '译文增加参数')
end
